//! The demo provider (debug builds only, `DASHCRAFT_AI_MOCK=1`): requests are planned with the
//! real adapter, so `ai.preview` and the consent dialog show exactly what would be sent, but
//! [`Provider::complete`] waits briefly (cancellable) and answers with canned text instead of
//! calling the endpoint. Enabling AI and recording consent are still required, so the whole UI
//! flow can be exercised offline.

use std::sync::Arc;
use std::time::Duration;

use pbi_ai::provider::HttpRequest;
use pbi_ai::{
    AiError, Capability, ChatRequest, ChatResponse, DefaultProviderFactory, Endpoint, MockProvider,
    MockReply, Provider, ProviderFactory, ProviderKind, ProviderSettings, Secret,
};
use pbi_ops::BoxFuture;
use pbi_session::CancellationToken;
use serde_json::{Value, json};

/// `DASHCRAFT_AI_MOCK` is `1` (or `true`).
pub fn requested(env: impl Fn(&str) -> Option<std::ffi::OsString>) -> bool {
    env("DASHCRAFT_AI_MOCK")
        .and_then(|v| v.into_string().ok())
        .is_some_and(|v| matches!(v.trim(), "1" | "true"))
}

/// How long a demo answer takes (long enough to see the progress and try Cancel).
const DELAY: Duration = Duration::from_millis(1500);

/// Builds every provider as a [`DemoProvider`] around the real adapter.
#[derive(Debug, Default, Clone, Copy)]
pub struct DemoFactory;

impl ProviderFactory for DemoFactory {
    fn create(
        &self,
        settings: &ProviderSettings,
        key: Option<Secret>,
    ) -> Result<Arc<dyn Provider>, AiError> {
        Ok(Arc::new(DemoProvider {
            real: DefaultProviderFactory.create(settings, key)?,
            canned: MockProvider::new(&settings.id),
        }))
    }
}

/// The real adapter for everything but sending.
#[derive(Debug)]
struct DemoProvider {
    real: Arc<dyn Provider>,
    canned: MockProvider,
}

impl Provider for DemoProvider {
    fn id(&self) -> &str {
        self.real.id()
    }

    fn kind(&self) -> ProviderKind {
        self.real.kind()
    }

    fn endpoint(&self) -> &Endpoint {
        self.real.endpoint()
    }

    fn http_request(&self, req: &ChatRequest) -> Result<HttpRequest, AiError> {
        self.real.http_request(req)
    }

    fn complete<'a>(
        &'a self,
        req: ChatRequest,
        cancel: CancellationToken,
    ) -> BoxFuture<'a, Result<ChatResponse, AiError>> {
        self.canned.push(MockReply::Delay(
            DELAY,
            Box::new(MockReply::Json(answer(req.capability))),
        ));
        self.canned.complete(req, cancel)
    }
}

/// The canned answer of `capability`. The explanation exercises the app's Markdown renderer,
/// including markup in model text that must stay inert.
fn answer(capability: Option<Capability>) -> Value {
    match capability {
        Some(Capability::DaxExplain) => json!({
            "summary": "Demo answer from DashCraft's debug demo provider: no model was called and nothing left this computer.",
            "explanation": "## What it computes\n\nThis **demo** explanation shows how answers are rendered: headings, *emphasis*, lists, `inline code` and code blocks.\n\n1. The measure is evaluated in the filter context of the visual or query that uses it.\n2. Filters on related tables reach it through active relationships.\n\n```dax\nEVALUATE\n    ROW ( \"Value\", [Measure] )\n```\n\nText from the model or the provider is untrusted and stays inert: <script>alert('x')</script>, <img src=x onerror=alert(1)> and [a link](https://example.com) are shown as plain text.",
            "filterContext": [
                "No row context: the value depends only on the filters of the visual, slicers, page and report.",
            ],
            "dependencies": [
                {"name": "(demo)", "note": "A real provider describes each referenced column and measure here."},
            ],
            "caveats": ["Generated by the debug demo provider (DASHCRAFT_AI_MOCK=1)."],
        }),
        Some(Capability::DaxGenerate) => json!({
            "name": "Demo ratio",
            "expression": "DIVIDE ( 1, 4 )",
            "formatString": "0.0%",
            "explanation": "The **demo provider** always suggests `DIVIDE ( 1, 4 )`: a constant ratio, formatted as a percentage. A real provider writes DAX for your request from the model's metadata.",
            "assumptions": ["Generated by the debug demo provider (DASHCRAFT_AI_MOCK=1)."],
        }),
        other => MockProvider::canned(other),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn only_explicit_values_turn_the_demo_on() {
        let with = |v: &'static str| move |_: &str| Some(std::ffi::OsString::from(v));
        assert!(requested(with("1")));
        assert!(requested(with("true")));
        assert!(!requested(with("0")));
        assert!(!requested(with("")));
        assert!(!requested(|_: &str| None));
    }

    #[test]
    fn previews_use_the_real_adapter() {
        let settings = ProviderSettings {
            id: "openai".into(),
            kind: ProviderKind::OpenAiCompatible,
            endpoint: Some("https://api.example.test/v1".into()),
            model: Some("m".into()),
            deployment: None,
            api_version: None,
            structured_output: None,
            allow_http: false,
            label: None,
        };
        let provider = DemoFactory
            .create(&settings, Some(Secret::new("sk-demo")))
            .unwrap();
        let preview = provider
            .http_request(&ChatRequest::new(Vec::new()))
            .unwrap()
            .preview();
        assert_eq!(preview.url, "https://api.example.test/v1/chat/completions");
        assert!(!serde_json::to_string(&preview).unwrap().contains("sk-demo"));
    }
}
