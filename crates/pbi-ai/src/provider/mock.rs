//! [`MockProvider`]: deterministic answers, no network.

use std::collections::VecDeque;
use std::sync::{Mutex, PoisonError};
use std::time::Duration;

use pbi_ops::BoxFuture;
use serde_json::{Value, json};
use tokio_util::sync::CancellationToken;

use super::http::HttpRequest;
use super::{ChatRequest, ChatResponse, Provider, Usage, messages_json};
use crate::capability::Capability;
use crate::endpoint::Endpoint;
use crate::error::AiError;
use crate::settings::ProviderKind;

/// One scripted answer.
#[derive(Debug, Clone)]
pub enum MockReply {
    /// Answer with this text.
    Text(String),
    /// Answer with this JSON (as text).
    Json(Value),
    /// Fail.
    Error(AiError),
    /// Wait (cancellable), then answer.
    Delay(Duration, Box<MockReply>),
}

/// A provider that answers from a script (in order; the canned answer of
/// the request's capability once the script is empty) and records every
/// request.
#[derive(Debug)]
pub struct MockProvider {
    id: String,
    endpoint: Endpoint,
    script: Mutex<VecDeque<MockReply>>,
    requests: Mutex<Vec<ChatRequest>>,
}

impl MockProvider {
    /// Canned answers only.
    #[must_use]
    pub fn new(id: &str) -> Self {
        Self::scripted(id, [])
    }

    /// Answers `replies` in order, then canned answers.
    #[must_use]
    pub fn scripted(id: &str, replies: impl IntoIterator<Item = MockReply>) -> Self {
        Self {
            id: id.to_owned(),
            endpoint: Endpoint::mock(id),
            script: Mutex::new(replies.into_iter().collect()),
            requests: Mutex::new(Vec::new()),
        }
    }

    /// Appends a scripted answer.
    pub fn push(&self, reply: MockReply) {
        self.script
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .push_back(reply);
    }

    /// Every request received, in order.
    #[must_use]
    pub fn requests(&self) -> Vec<ChatRequest> {
        self.requests
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .clone()
    }

    /// Number of requests received.
    #[must_use]
    pub fn calls(&self) -> usize {
        self.requests
            .lock()
            .unwrap_or_else(PoisonError::into_inner)
            .len()
    }

    /// The canned answer of `capability`.
    #[must_use]
    pub fn canned(capability: Option<Capability>) -> Value {
        match capability {
            Some(Capability::DaxExplain) => json!({
                "summary": "Mock explanation: this answer comes from the mock provider; no model was called.",
                "explanation": "The **mock provider** returns this fixed text so that front ends and tests can run without a model.",
                "filterContext": ["The measure is evaluated in the filter context of the visual or query that uses it."],
                "dependencies": [],
                "caveats": ["Generated by the mock provider."],
            }),
            Some(Capability::DaxGenerate) => json!({
                "name": "Mock measure",
                "expression": "1",
                "formatString": null,
                "explanation": "The mock provider always suggests the constant 1.",
                "assumptions": ["Generated by the mock provider."],
            }),
            _ => json!({}),
        }
    }
}

impl Provider for MockProvider {
    fn id(&self) -> &str {
        &self.id
    }

    fn kind(&self) -> ProviderKind {
        ProviderKind::Mock
    }

    fn endpoint(&self) -> &Endpoint {
        &self.endpoint
    }

    fn http_request(&self, req: &ChatRequest) -> Result<HttpRequest, AiError> {
        Ok(HttpRequest {
            method: "MOCK",
            url: self.endpoint.join("chat"),
            headers: Vec::new(),
            body: json!({
                "messages": messages_json(req),
                "temperature": req.temperature,
                "max_tokens": req.max_tokens,
                "response_schema": req.response_schema.as_ref().map(|s| &s.schema),
            }),
        })
    }

    fn complete<'a>(
        &'a self,
        req: ChatRequest,
        cancel: CancellationToken,
    ) -> BoxFuture<'a, Result<ChatResponse, AiError>> {
        Box::pin(async move {
            let capability = req.capability;
            self.requests
                .lock()
                .unwrap_or_else(PoisonError::into_inner)
                .push(req);
            let mut reply = self
                .script
                .lock()
                .unwrap_or_else(PoisonError::into_inner)
                .pop_front()
                .unwrap_or_else(|| MockReply::Json(Self::canned(capability)));
            loop {
                if cancel.is_cancelled() {
                    return Err(AiError::Cancelled);
                }
                let content = match reply {
                    MockReply::Text(text) => text,
                    MockReply::Json(v) => v.to_string(),
                    MockReply::Error(e) => return Err(e),
                    MockReply::Delay(d, next) => {
                        tokio::select! {
                            biased;
                            () = cancel.cancelled() => return Err(AiError::Cancelled),
                            () = tokio::time::sleep(d) => {}
                        }
                        reply = *next;
                        continue;
                    }
                };
                return Ok(ChatResponse {
                    content,
                    model: Some("mock".into()),
                    finish_reason: Some("stop".into()),
                    usage: Usage::default(),
                });
            }
        })
    }
}
